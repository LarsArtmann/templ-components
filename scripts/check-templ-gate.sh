#!/usr/bin/env bash
# check-templ-gate.sh — templ pin ↔ generator lockstep probe (TODO #335,
# window EXECUTED 2026-11-04). Read-only: prints whether the lockstep gate
# is OPEN or CLOSED and, when open, the repair recipe. Never fails on a
# closed gate — closed is the correct resting state; the script exists so
# the re-check is one command instead of archaeology.
#
# INVARIANT (changed with the migration): the generator is the flake's
# `templGen` derivation, built from the true upstream a-h/templ tag — NOT
# nixpkgs (nixpkgs lags and its templ version string cannot be trusted).
# The zero-diff-generate contract is therefore: flake templGen rev ==
# every go.mod pin. The gate OPENS when they diverge (a daemon bumped one
# side, or an upstream release is being adopted), and the recipe is the
# one-event plan of record.
#
# History: templ >= v0.3.1100 DELETED templ.ResolveAttributeValue /
# templ.RenderAttributes / templ.JoinURLErs (upstream ADR-0004 attribute
# sanitization — the removal IS the security fix delivery mechanism). The
# committed generated files must always be regenerated by the SAME version
# as the go.mod pin in one release event.

set -euo pipefail
cd "$(dirname "$0")/.."

PIN="$(sed -n 's/.*github.com\/a-h\/templ \(v[0-9.]*\).*/\1/p' go.mod | head -1)"
GEN="$(sed -n '/templGen = /,/^          };/s/.*rev = "\(v[0-9.]*\)".*/\1/p' flake.nix | head -1)"

if [ -z "$PIN" ]; then
	echo "ERROR: could not parse the templ pin from go.mod" >&2
	exit 1
fi
if [ -z "$GEN" ]; then
	echo "ERROR: could not parse the templGen rev from flake.nix" >&2
	exit 1
fi

echo "go.mod pin:         $PIN"
echo "flake templGen rev: $GEN"

if [ "$PIN" = "$GEN" ]; then
	echo "GATE: CLOSED — pin and generator are in lockstep; nothing to migrate."
	exit 0
fi

echo ""
echo "GATE: OPEN — go.mod pin ($PIN) and flake generator ($GEN) diverge."
echo "Recipe (ONE release event, per the plan of record):"
echo "  1. Align BOTH sides to the target version in ONE commit (all 9 go.mod"
echo "     pins + doctor.go templGeneratedWith + the flake templGen rev)."
echo "  2. Regenerate with the flake generator: nix run .#build (root +"
echo "     per-module GOWORK=off, canonical FileName form)."
echo "  3. Re-record HTML goldens (-update) AND pixel visual goldens"
echo "     (nix run .#visual -- -update) in the SAME event."
echo "  4. Verify: rg -l ResolveAttributeValue --glob '*_templ.go' | wc -l -> 0"
echo "  5. Full verify + ci-repro, then ONE release cut stating the new"
echo "     minimum templ pairing."
echo "Plan of record: docs/planning/ (TEMPL-MIGRATION-WINDOW-PLAN)."
exit 0
