package pages

import (
	"bytes"
	"context"
	"fmt"
	stdhtml "html"
	"io"

	"github.com/a-h/templ"
	"github.com/alecthomas/chroma/v2"
	chromahtml "github.com/alecthomas/chroma/v2/formatters/html"
	"github.com/alecthomas/chroma/v2/lexers"
	"github.com/alecthomas/chroma/v2/styles"
)

// lexerFor resolves a fence language to a chroma lexer. templ fences
// highlight as Go (close enough for keyword/string coloring; chroma has no
// dedicated templ lexer).
func lexerFor(lang string) chroma.Lexer {
	if l := lexers.Get(lang); l != nil {
		return l
	}
	if lang == "templ" {
		return lexers.Get("go")
	}
	return nil
}

// highlight renders source code to chroma-highlighted HTML using class-based
// tokens (no inline styles — CSP-safe). Colors come from the site stylesheet,
// which scopes github-light/github-dark token classes under the theme class.
func highlight(source, lang string) (templ.Component, error) {
	lexer := lexerFor(lang)
	if lexer == nil {
		escaped := stdhtml.EscapeString(source)
		return templ.FromHTMLString(`<pre class="chroma"><code>` + escaped + "</code></pre>")
	}
	iterator, err := lexer.Tokenise(nil, source)
	if err != nil {
		return nil, fmt.Errorf("tokenise %s snippet: %w", lang, err)
	}
	formatter := chromahtml.New(chromahtml.WithClasses(true))
	var buf bytes.Buffer
	// The style only drives class emission here; actual colors live in the
	// dual-theme CSS generated by cmd/site (github-light + github-dark).
	if err := formatter.Format(&buf, styles.Get("github-dark"), iterator); err != nil {
		return nil, fmt.Errorf("format %s snippet: %w", lang, err)
	}
	return templ.FromHTMLString(buf.String())
}

// highlightTempl highlights a templ source snippet for the hero window.
func highlightTempl(source string) templ.Component {
	return templ.ComponentFunc(func(ctx context.Context, w io.Writer) error {
		c, err := highlight(source, "templ")
		if err != nil {
			return err
		}
		return c.Render(ctx, w)
	})
}
